import { assertEquals, assertThrows } from "@test/assert";
import {
    VALID_CA_PEM,
    EXPIRED_CA_PEM,
    FUTURE_CA_PEM,
    LEAF_CERT_PEM
} from "../../test/fixtures/upstreamCaCertificates";
import {
    MAX_UPSTREAM_CA_PEM_LENGTH,
    MAX_UPSTREAM_CA_CERTIFICATES,
    normalizeUpstreamCaPem
} from "./upstreamCa";

// Long-lived test fixtures keep the suite stable across releases.
const caPem = VALID_CA_PEM;

const annotatedBundle = `# Generated by step-ca
name: Homelab Root
${caPem}
# Intermediate CA
issuer: Homelab Root
${caPem}`;

assertEquals(
    normalizeUpstreamCaPem(annotatedBundle),
    caPem + caPem,
    "Metadata around valid certificates should be ignored"
);

assertEquals(
    normalizeUpstreamCaPem(caPem),
    caPem,
    "A single valid certificate should be preserved"
);

assertThrows(
    () =>
        normalizeUpstreamCaPem(
            caPem + "\n-----BEGIN CERTIFICATE-----\ntruncated"
        ),
    "incomplete PEM",
    "An incomplete additional PEM block must be rejected"
);

assertThrows(
    () => normalizeUpstreamCaPem("-----END CERTIFICATE-----\n" + caPem),
    "incomplete PEM",
    "An orphan END marker must be rejected"
);

assertThrows(
    () => normalizeUpstreamCaPem(caPem + "\n-----BEGIN PRIVATE KEY-----\n..."),
    "private key",
    "Private key material must be rejected"
);

assertThrows(
    () =>
        normalizeUpstreamCaPem(
            "-----BEGIN CERTIFICATE-----\ninvalid\n-----END CERTIFICATE-----"
        ),
    "could not parse PEM",
    "Invalid X.509 material must be rejected"
);

assertThrows(
    () => normalizeUpstreamCaPem("# comment only"),
    "no PEM-encoded certificate found",
    "An empty certificate bundle must be rejected"
);

assertThrows(
    () => normalizeUpstreamCaPem("#".repeat(MAX_UPSTREAM_CA_PEM_LENGTH + 1)),
    "maximum allowed size",
    "Oversize input must be rejected"
);

assertThrows(
    () =>
        normalizeUpstreamCaPem(caPem.repeat(MAX_UPSTREAM_CA_CERTIFICATES + 1)),
    "at most",
    "Oversize certificate bundles must be rejected"
);

assertThrows(
    () => normalizeUpstreamCaPem(LEAF_CERT_PEM),
    "CA:TRUE",
    "A server/leaf certificate must not be accepted as a trusted CA"
);

assertThrows(
    () => normalizeUpstreamCaPem(EXPIRED_CA_PEM),
    "expired",
    "An expired CA must not be accepted"
);

assertThrows(
    () => normalizeUpstreamCaPem(FUTURE_CA_PEM),
    "not yet valid",
    "A CA that is not valid yet must not be accepted"
);

assertThrows(
    () => normalizeUpstreamCaPem(VALID_CA_PEM + EXPIRED_CA_PEM),
    "expired",
    "One expired certificate must invalidate an entire CA bundle"
);

assertThrows(
    () => normalizeUpstreamCaPem(VALID_CA_PEM + LEAF_CERT_PEM),
    "CA:TRUE",
    "One leaf certificate must invalidate an entire CA bundle"
);

console.log("Upstream CA normalization tests passed!");
